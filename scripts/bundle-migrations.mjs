// Turns drizzle-kit output (drizzle/*.sql + meta/_journal.json) into src/data/db/migrations.gen.ts.
// The app and Node tests import the same generated module; no fs access at runtime.
// Run via `npm run db:generate` (drizzle-kit generate && this script).
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const journal = JSON.parse(
	readFileSync(resolve(root, "drizzle/meta/_journal.json"), "utf8"),
);
const migrations = journal.entries
	.sort((a, b) => a.idx - b.idx)
	.map((entry) => ({
		id: entry.tag,
		statements: readFileSync(resolve(root, `drizzle/${entry.tag}.sql`), "utf8")
			.split("--> statement-breakpoint")
			.map((statement) => statement.trim())
			.filter(Boolean),
	}));

const out = `// GENERATED by scripts/bundle-migrations.mjs from drizzle/. Do not edit.
export const migrations: ReadonlyArray<{ id: string; statements: readonly string[] }> = ${JSON.stringify(migrations, null, "\t")};
`;
writeFileSync(resolve(root, "src/data/db/migrations.gen.ts"), out);
console.log(`bundled ${migrations.length} migration(s): ${migrations.map((m) => m.id).join(", ")}`);
